import assert from "node:assert/strict";
import { groupSongMixes, songMixKey } from "../src/models/songMixes";
import { parseReleasePublicationTargets } from "../server/utils/publication/releasePublicationTargets";
const rows = Array.from({ length: 111 }, (_, index) => ({ id: `release-${index}`, selected: undefined as unknown }));
const grouped = groupSongMixes(rows, row => row.id, row => row.selected);
assert.equal(grouped.length, 3);
assert.equal(grouped.reduce((sum, mix) => sum + mix.items.length, 0), 111);
assert.ok(grouped.every(mix => mix.items.length >= 15));
assert.equal(new Set(grouped.flatMap(mix => mix.items.map(item => item.id))).size, 111);
assert.deepEqual(groupSongMixes([...rows, rows[0]], row => row.id, row => row.selected), grouped);
for (const row of rows) assert.equal(songMixKey(row.id), songMixKey(row.id));
assert.equal(songMixKey("release", "nexus-03"), "nexus-03");
for (const value of ["unknown", "", null, false, ["nexus-01"]]) assert.equal(parseReleasePublicationTargets({ publicationPlaylist: value }), null);
assert.ok(parseReleasePublicationTargets({}));
assert.ok(parseReleasePublicationTargets({ publicationPlaylist: "auto" }));
assert.equal(parseReleasePublicationTargets({ publicationAudience: "vip", publicationPlaylist: "nexus-01" })?.audience, "vip", "Mix assignment must not change audience");
const authorizedOnly = rows.slice(0, 5);
assert.equal(groupSongMixes(authorizedOnly, row => row.id, row => row.selected).flatMap(mix => mix.items).length, 5, "Grouping must never fetch or add missing content");
console.log("Song mix tests passed: three deterministic groups, 111 unique songs, explicit assignment, legacy defaults, invalid config denial and audience isolation.");
